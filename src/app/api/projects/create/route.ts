import { NextRequest, NextResponse } from "next/server";
import { db } from "@/lib/db";
import { requireUser } from "@/lib/auth";

export async function POST(request: NextRequest) {
  try {
    const user = await requireUser();
    const body = await request.json();
    const { name, description } = body;

    if (!name || name.trim().length === 0) {
      return NextResponse.json({ error: "Project name is required" }, { status: 400 });
    }

    const project = await db.project.create({
      data: {
        userId: user.id,
        name: name.trim(),
        description: description?.trim() || null,
      },
    });

    // Create default starter files
    await db.projectFile.createMany({
      data: [
        {
          projectId: project.id,
          path: "README.md",
          content: `# ${name}\n\nWelcome to your Mystic AI project workspace.\n\n## Getting Started\n\nThis project was created in the Mystic AI workspace. Use the Mystic Fusion Engine to plan and execute tasks.\n\n## Files\n\nGenerated files will appear here as tasks complete.\n`,
          language: "markdown",
        },
        {
          projectId: project.id,
          path: "index.html",
          content: `<!DOCTYPE html>\n<html lang="en">\n<head>\n  <meta charset="UTF-8">\n  <title>${name}</title>\n</head>\n<body>\n  <h1>${name}</h1>\n  <p>Generated by Mystic AI</p>\n</body>\n</html>\n`,
          language: "html",
        },
      ],
    });

    return NextResponse.json({ project });
  } catch (err) {
    return NextResponse.json({ error: err instanceof Error ? err.message : "Failed" }, { status: 500 });
  }
}

export async function GET() {
  try {
    const user = await requireUser();
    const project = await db.project.create({
      data: {
        userId: user.id,
        name: "Untitled Project",
        description: "",
      },
    });
    return NextResponse.json({ project });
  } catch (err) {
    return NextResponse.json({ error: err instanceof Error ? err.message : "Failed" }, { status: 500 });
  }
}
